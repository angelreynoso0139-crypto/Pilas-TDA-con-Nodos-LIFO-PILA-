    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String cod = "p-" + System.currentTimeMillis() % 1000;
            String t = txtTitulo.getText().trim();
            String g = txtGenero.getText().trim();
            int d = Integer.parseInt(txtDuracion.getText().trim());
            String c = txtClasificacion.getText().trim();
            String p = txtRutaPoster.getText().trim();
            
            pila.apilar(new modelo.Pelicula(cod,t, g, d, c, p));
           
            renderizarPila();
            
            txtTitulo.setText("");
            txtGenero.setText("");
            txtDuracion.setText("");
            txtClasificacion.setText("");
            txtRutaPoster.setText("");
        } catch (NumberFormatException e){
            javax.swing.JOptionPane.showMessageDialog(this, "La duracion debe ser de un numero entero");
        } catch (Exception e){
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
              
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            modelo.Pelicula removida = pila.desapilar();
            renderizarPila();
            javax.swing.JOptionPane.showMessageDialog(this, "Se desapilo:" + removida.getTitulo());
        } catch (Exception e){
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

