    private void renderizarPila() {
        javax.swing.JPanel panelInterno = (javax.swing.JPanel) panelContenedorPila.getViewport().getView();
        if (panelInterno != null) {
            panelInterno.removeAll();
            estructura.Nodo actual = pila.getTopeNodo();
            
            while (actual != null) {
                PanelPeliculaItem item = new PanelPeliculaItem();
                item.cargarDatos(actual.getDato());
                panelInterno.add(item);
                panelInterno.add(javax.swing.Box.createRigidArea(new java.awt.Dimension(0, 10)));
                actual = actual.getSiguiente();
            }
            
            panelInterno.revalidate();
            panelInterno.repaint();
        }
    }

